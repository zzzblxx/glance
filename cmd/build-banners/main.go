// build-banners packages the user-provided JPEGs as firmware-local Gray4 RLE.
// No scaling, cropping, font substitution, or network dependency is involved.
package main

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"image/color"
	"image/jpeg"
	"os"
	"path/filepath"
)

func main() {
	if err := build(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func build() error {
	var out bytes.Buffer
	out.WriteString("// Generated by go run ./cmd/build-banners; do not edit.\n#pragma once\n#include <cstdint>\n#include <cstddef>\n#include <cstring>\nnamespace banner_assets {\nconstexpr int Width=704, Height=176;\nstruct Asset { const uint8_t* data; size_t size; };\n")
	ids := []string{"sprint", "cruise", "snack", "sleep"}
	total := 0
	for _, id := range ids {
		path := filepath.Join("assets/banners", id+".jpg")
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		img, err := jpeg.Decode(bytes.NewReader(raw))
		if err != nil {
			return err
		}
		if img.Bounds().Dx() != 704 || img.Bounds().Dy() != 176 {
			return fmt.Errorf("%s: expected 704 x 176", path)
		}
		gray := make([]byte, 0, 704*176)
		for y := 0; y < 176; y++ {
			for x := 0; x < 704; x++ {
				g := color.GrayModel.Convert(img.At(x, y)).(color.Gray).Y
				gray = append(gray, byte((int(g)*15+127)/255))
			}
		}
		var packed []byte
		for i := 0; i < len(gray); {
			n := 1
			for n < 16 && i+n < len(gray) && gray[i+n] == gray[i] {
				n++
			}
			packed = append(packed, byte(n-1)<<4|gray[i])
			i += n
		}
		total += len(packed)
		fmt.Fprintf(&out, "// %s SHA256 %x\nstatic const uint8_t %s[]={\n", id, sha256.Sum256(raw), id)
		for i, b := range packed {
			if i%24 == 0 {
				out.WriteString("  ")
			}
			fmt.Fprintf(&out, "0x%02x,", b)
			if i%24 == 23 {
				out.WriteByte('\n')
			}
		}
		out.WriteString("\n};\n")
	}
	out.WriteString("inline Asset find(const char* id) {\n  if (!id) return {nullptr,0};\n")
	for _, id := range ids {
		fmt.Fprintf(&out, "  if (!strcmp(id,\"%s\")) return {%s,sizeof(%s)};\n", id, id, id)
	}
	out.WriteString("  return {nullptr,0};\n}\n} // namespace banner_assets\n")
	if err := os.WriteFile("firmware/shared/banner_assets.h", out.Bytes(), 0644); err != nil {
		return err
	}
	fmt.Printf("Embedded four 704 x 176 Gray4 banners: %d RLE bytes total.\n", total)
	return nil
}
